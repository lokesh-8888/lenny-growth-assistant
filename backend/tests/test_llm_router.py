@pytest.mark.asyncio
async def test_ollama_provider_direct_mock():
    """Test OllamaProvider direct completion parsing."""
    from unittest.mock import MagicMock
    provider = OllamaProvider(base_url="http://localhost:11434", model="llama3.2:3b")

    mock_resp = MagicMock()
    mock_resp.status_code = 200
    mock_resp.json.return_value = {
        "message": {"content": "Ollama local response."},
        "prompt_eval_count": 10,
        "eval_count": 12,
    }

    with patch("httpx.AsyncClient.post", new_callable=AsyncMock, return_value=mock_resp):
        resp = await provider.complete(prompt="What is product strategy?")
        assert resp.content == "Ollama local response."
        assert resp.model == "llama3.2:3b"
        assert resp.provider == "ollama"
        assert resp.served_by == "ollama"
        assert resp.usage["total_tokens"] == 22


