def test_get_config_endpoint(client: TestClient):
    """Test GET /api/config endpoint response structure."""
    resp = client.get("/api/config")
    assert resp.status_code == 200
    data = resp.json()
    assert "current_provider" in data
    assert "current_model" in data
    assert data["fallback_provider"] == "ollama"
    assert "fallback_model" in data
    assert isinstance(data["available_providers"], list)
    assert "ollama" in data["available_providers"]
    assert "cloud_configured" in data
