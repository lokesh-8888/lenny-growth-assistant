@pytest.mark.asyncio
async def test_router_ollama_primary(mock_ollama_provider, mock_cloud_provider):
    """Test that LLMRouter with primary='ollama' routes directly to Ollama."""
    router = LLMRouter(
        primary_provider="ollama",
        ollama_provider=mock_ollama_provider,
        cloud_provider=mock_cloud_provider,
    )

    resp = await router.complete(prompt="Explain growth loops.")
    assert resp.content == "This is an answer generated locally by Ollama."
    assert resp.served_by == "ollama"
    mock_ollama_provider.complete.assert_called_once()
    mock_cloud_provider.complete.assert_not_called()


