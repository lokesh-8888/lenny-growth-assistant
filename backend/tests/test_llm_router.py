@pytest.mark.asyncio
async def test_router_fallback_on_missing_api_key(mock_ollama_provider, mock_cloud_provider):
    """Test that missing cloud API key triggers seamless Ollama fallback without throwing."""
    mock_cloud_provider.is_available.return_value = False

    router = LLMRouter(
        primary_provider="cloud",
        ollama_provider=mock_ollama_provider,
        cloud_provider=mock_cloud_provider,
    )

    resp = await router.complete(prompt="Explain virality.")
    assert resp.content == "This is an answer generated locally by Ollama."
